#!/usr/bin/env node
/* Builds site/schools/quiz-data.js from data/quiz-facts.json (structured facts per school)
   plus each school file's name, state and vibe meters. Run after changing either.
   Usage: node tools/build-quiz-data.js */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'site', 'schools');
const facts = JSON.parse(fs.readFileSync(path.join(root, 'data', 'quiz-facts.json'), 'utf8'));
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(dir, 'index.js'), 'utf8'), ctx);
const list = ctx.window.SCHOOL_LIST;
const order = ctx.window.SCHOOL_ORDER;

const out = {};
const problems = [];
list.forEach(entry => {
  let s = null;
  vm.runInNewContext(fs.readFileSync(path.join(dir, entry.id + '.js'), 'utf8'), { registerSchool: d => { s = d; } });
  const f = facts[entry.id];
  if (!f) { problems.push(entry.id + ': no facts'); return; }
  const meters = {};
  Object.keys(s.sections.vibe.meters).forEach(k => { meters[k] = s.sections.vibe.meters[k].value; });
  out[entry.id] = Object.assign({
    name: entry.name,
    short: s.title || s.name,
    state: entry.location.split(', ')[1],
    town: entry.location.split(',')[0],
    rank: order.indexOf(entry.id),
    band: entry.band,
    meters: meters
  }, f);
});

fs.writeFileSync(path.join(dir, 'quiz-data.js'),
  '/* Generated by tools/build-quiz-data.js. Do not edit by hand; edit data/quiz-facts.json or the school files. */\n' +
  'window.QUIZ_DATA = ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length + ' schools written' + (problems.length ? '; problems: ' + problems.join(', ') : ''));
